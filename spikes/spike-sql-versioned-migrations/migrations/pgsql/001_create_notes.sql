-- 001: schema FINAL da tabela de exemplo. IF NOT EXISTS mantém a migration segura
-- em bancos onde a tabela já foi criada antes do versionamento.
-- PostgreSQL: identidade padrão SQL no lugar de AUTO_INCREMENT; não existe
-- ON UPDATE CURRENT_TIMESTAMP, então updated_at é mantido pela aplicação (ou por trigger).
CREATE TABLE IF NOT EXISTS notes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
